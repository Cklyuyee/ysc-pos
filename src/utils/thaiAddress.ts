export function lookupByZipcode(zipcode: string): ThaiAddressEntry[] {
  if (!zipcode || zipcode.length !== 5) return [];
  return RAW
    .filter(([, , , z]) => z === zipcode)
    .map(([tambon, amphoe, province, zip]) => ({ tambon, amphoe, province, zipcode: zip }));
}
